"""Inventory of game object classes: factory entry -> ctor -> vtable -> slots overriding the
generic object (CLASS_OBJECT -107, vtable 1038:40de). Output: docs/re/classes.md.

Usage: python3 tools/class_inventory.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import vtable as vt  # noqa: E402
from nelib import Ne  # noqa: E402

BASE = "1038:40de"


def slots(ne, addr):
    import io
    import contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        vt.main([addr])
    out = {}
    for line in buf.getvalue().splitlines()[1:]:
        f = line.split()
        out[int(f[0], 16)] = f[1]
    return out


def main():
    ne = Ne("original/extracted/APP/PEST.EXE")
    src = open("work/ghidra/pest.c").read()
    factory = re.search(r"// ==== CreateObjectForModule.*?(?=// ==== )", src, re.S).group(0)
    entries = re.findall(r"iVar1 == (-?0x[0-9a-f]+|-?\d+)\)\s*\{\s*puVar2 = \(undefined2 \*\)operator_new\((0x[0-9a-f]+|\d+)\);"
                         r".*?puVar5 = (FUN_\w+)\(", factory, re.S)
    base = slots(ne, BASE)
    lines = ["# Object classes (generated by tools/class_inventory.py)", "",
             "Base: CLASS_OBJECT -107, vtable `1038:40de`. Overridden slots must be ported per class.", "",
             "| class | size | ctor | vtable | overridden slots (offset=function) |", "|---|---|---|---|---|"]
    for cls, size, ctor in entries:
        c = int(cls, 16) if "x" in cls else int(cls)
        ctor_addr = ctor.replace("FUN_", "").replace("_", ":")
        body = re.search(r"// ==== \S+ @ " + re.escape(ctor_addr) + r".*?(?=// ==== )", src, re.S)
        vts = re.findall(r"\*param_1 = (0x[0-9a-f]+);", body.group(0)) if body else []
        if not vts:
            lines.append(f"| {c} | {size} | {ctor_addr} | ? | |")
            continue
        vaddr = f"1038:{int(vts[-1], 16):04x}"
        s = slots(ne, vaddr)
        over = [f"+0x{k:02x}={v}" for k, v in sorted(s.items()) if k <= 0x68 and base.get(k) != v]
        lines.append(f"| {c} | {size} | {ctor_addr} | {vaddr} | {' '.join(over)} |")
    open("docs/re/classes.md", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
